import manifest from '../data/image-manifest.json'

// Most content images are single-column on mobile/tablet and two-column on desktop.
export const DEFAULT_SIZES = '(max-width: 1024px) 100vw, 50vw'
// Team portraits and dense grids render smaller cards on large screens.
export const GRID_CARD_SIZES = '(max-width: 640px) 100vw, (max-width: 1024px) 50vw, 25vw'
// Masonry album thumbnails are narrower as the number of columns increases.
export const ALBUM_SIZES = '(max-width: 640px) 50vw, (max-width: 1024px) 50vw, (max-width: 1280px) 33vw, 25vw'
export const HERO_SIZES = '100vw'

const images = manifest.images || {}

/** Gallery photos: every file in public/images/galerie/, sorted by file name. */
export const galleryPhotos = manifest.gallery || []

/** Metadata of an image generated by scripts/optimize-images.mjs, or undefined. */
export const getImageInfo = (src) => images[src]

/**
 * srcset listing only the optimized WebP versions that really exist.
 * Returns undefined for images that are not in the manifest (SVG, external URL…),
 * so the browser simply uses `src`.
 */
export const buildSrcSet = (src) => {
	const info = images[src]
	if (!info) return undefined
	return info.widths.map((width) => `/images/optimized/${info.key}-${width}.webp ${width}w`).join(', ')
}

/** Largest optimized version, handy where a single URL is needed (preload, background…). */
export const optimizedSrc = (src, maxWidth = Infinity) => {
	const info = images[src]
	if (!info) return src
	const candidates = info.widths.filter((width) => width <= maxWidth)
	const width = candidates.length ? candidates[candidates.length - 1] : info.widths[0]
	return `/images/optimized/${info.key}-${width}.webp`
}
